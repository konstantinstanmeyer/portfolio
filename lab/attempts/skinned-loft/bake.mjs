// node bake.mjs  -> writes data.js (compact baked geometry + skin data)
import { writeFileSync } from 'node:fs';
import { generate } from './generate.js';

const t0 = performance.now();
const d = generate({});
const ms = (performance.now() - t0).toFixed(0);
const { stats, ...data } = d;
console.log('bake', ms + 'ms', JSON.stringify(stats));
const out = `// AUTO-GENERATED by bake.mjs from generate.js — do not edit by hand.
// Low-poly lofted human mannequin: indexed mesh + skin data + bind-pose bones (meters, +Z forward).
export const FIGURE_DATA = ${JSON.stringify(data)};
`;
writeFileSync(new URL('./data.js', import.meta.url), out);
console.log('data.js', (out.length / 1024).toFixed(1) + 'KB', 'verts', data.positions.length / 3, 'tris', data.indices.length / 3);
